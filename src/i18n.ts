export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: 'fr', setLang: () => {} })

export function useLang() {
  return useContext(LangContext)
}

export function useT(): Dict {
  return useLang().lang === 'en' ? EN : FR
}

export function readLang(): Lang {
  try {
    const l = localStorage.getItem('vj-lang')
    if (l === 'en' || l === 'fr') return l
  } catch {
    /* storage blocked */
  }
  return navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'fr'
}

export function writeLang(l: Lang): void {
  try {
    localStorage.setItem('vj-lang', l)
  } catch {
    /* storage blocked */
  }
}
